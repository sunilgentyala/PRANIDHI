"""
PPHB-lite: a small, reproducible, fully-synthetic prompt corpus.

Unlike the 10,247-prompt "PPHB" benchmark described in earlier project
drafts (which was never actually built), this corpus is real: every prompt
below is generated by this file, checked into the repo indirectly via its
generator, and inspectable line by line. It exists to give the evaluation
in benchmarks/run_evaluation.py real, reproducible input rather than
invented numbers.

Every prompt is templated and every entity (names, companies, account
numbers, keys) is synthetic. Ground-truth labels are attached at
generation time so detection quality can be measured against a known
answer, independent of whatever the pipeline itself decides.
"""

from __future__ import annotations

import random
from dataclasses import dataclass, field


@dataclass(frozen=True)
class CorpusItem:
    prompt: str
    vertical: str
    role: str
    department: str
    target_platform: str
    has_pii: bool
    has_credential: bool
    has_code: bool
    is_benign: bool
    category: str


VERTICALS = ["financial_services", "healthcare", "technology", "legal", "manufacturing"]
ROLES = ["analyst", "engineer", "manager", "security", "legal_counsel", "intern"]
DEPARTMENTS = ["risk", "engineering", "sales", "compliance", "hr", "operations"]
PLATFORMS = ["claude", "chatgpt", "perplexity", "grok", "gemini", "internal"]

# Synthetic entities only: placeholder companies and example.com addresses.
FAKE_COMPANIES = ["Acme Corp", "Globex", "Initech", "Umbrella Retail", "Wayne Logistics",
                   "Stark Diagnostics", "Wonka Foods", "Hooli Systems", "Soylent Health"]
FAKE_NAMES = ["Jordan Lee", "Priya Anand", "Sam Whitfield", "Maria Gonzalez", "Tom O'Brien",
              "Chen Wei", "Fatima Noor", "Alex Petrov", "Grace Okafor", "Liam Sato"]


def _fake_email(name: str) -> str:
    local = name.lower().replace(" ", ".").replace("'", "")
    return f"{local}@example.com"


def _fake_ssn(rng: random.Random) -> str:
    return f"{rng.randint(100,899):03d}-{rng.randint(10,99):02d}-{rng.randint(1000,9999):04d}"


def _fake_account(rng: random.Random) -> str:
    return f"account #{rng.randint(1000,9999)}-{rng.randint(1000,9999)}"


def _fake_api_key(rng: random.Random) -> str:
    # Deliberately not shaped like a real provider's key prefix (e.g. Stripe's
    # "sk_live_"): this is a synthetic corpus, and using a real vendor's format
    # would make the string indistinguishable from an actual leaked credential
    # to secret-scanning tooling.
    charset = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
    body = "".join(rng.choice(charset) for _ in range(32))
    return f"secret_synthetic_{body}"


def _fake_revenue_pct(rng: random.Random) -> float:
    return round(rng.uniform(8.0, 22.0), 1)


BENIGN_TEMPLATES = [
    "What frameworks exist for analysing {pct}% revenue declines in a single quarter?",
    "Summarise the key differences between REST and gRPC for internal API design.",
    "Draft a generic incident response checklist for a phishing report.",
    "What are common causes of false positives in anomaly detection systems?",
    "Explain the tradeoffs between symmetric and asymmetric encryption for data at rest.",
    "Suggest three discussion questions for a workshop on AI governance frameworks.",
    "How should a manufacturing plant structure a preventive maintenance schedule?",
    "What NIST controls apply to third-party vendor risk assessments?",
]

PII_TEMPLATES = [
    "Analyse {name}'s account, contactable at {email}, for unusual transaction patterns.",
    "Draft a follow-up email to {name} ({email}) regarding their overdue invoice.",
    "Employee {name}, SSN {ssn}, needs their payroll record corrected for this quarter.",
    "Please summarise the support ticket history for {name} ({email}) at {company}.",
]

CREDENTIAL_TEMPLATES = [
    "Here is our production key {key}: can you check why the integration is failing?",
    "Use this token to pull the latest report: {key}",
    "I think this API key {key} might be leaked, can you check the logs for misuse?",
]

CODE_TEMPLATES = [
    "def calculate_quarterly_revenue(records):\n    return sum(r['amount'] for r in records)",
    "SELECT customer_id, balance FROM accounts WHERE balance > 100000;",
    "class RiskModel:\n    def __init__(self, weights):\n        self.weights = weights",
]

FINANCIAL_LEAK_TEMPLATES = [
    "Why did {company}'s Q3 revenue drop {pct}% after losing their largest client?",
    "Draft a board memo explaining {company}'s {pct}% margin contraction and {name}'s role in the account loss.",
    "Analyse {company}'s {acct} for signs of fraud given their {pct}% unexplained variance.",
]


def generate_corpus(size: int = 400, seed: int = 20260721) -> list[CorpusItem]:
    """Generate a deterministic, fully-synthetic labeled prompt corpus."""
    rng = random.Random(seed)
    items: list[CorpusItem] = []

    category_weights = [
        ("benign", BENIGN_TEMPLATES, dict(has_pii=False, has_credential=False, has_code=False, is_benign=True)),
        ("pii", PII_TEMPLATES, dict(has_pii=True, has_credential=False, has_code=False, is_benign=False)),
        ("credential", CREDENTIAL_TEMPLATES, dict(has_pii=False, has_credential=True, has_code=False, is_benign=False)),
        ("code", CODE_TEMPLATES, dict(has_pii=False, has_credential=False, has_code=True, is_benign=False)),
        ("financial_leak", FINANCIAL_LEAK_TEMPLATES, dict(has_pii=True, has_credential=False, has_code=False, is_benign=False)),
    ]

    per_category = size // len(category_weights)

    for category, templates, gt in category_weights:
        for _ in range(per_category):
            template = rng.choice(templates)
            name = rng.choice(FAKE_NAMES)
            company = rng.choice(FAKE_COMPANIES)
            prompt = template.format(
                name=name,
                email=_fake_email(name),
                ssn=_fake_ssn(rng),
                company=company,
                key=_fake_api_key(rng),
                acct=_fake_account(rng),
                pct=_fake_revenue_pct(rng),
            )
            items.append(CorpusItem(
                prompt=prompt,
                vertical=rng.choice(VERTICALS),
                role=rng.choice(ROLES),
                department=rng.choice(DEPARTMENTS),
                target_platform=rng.choice(PLATFORMS),
                category=category,
                **gt,
            ))

    rng.shuffle(items)
    return items


if __name__ == "__main__":
    corpus = generate_corpus()
    print(f"Generated {len(corpus)} synthetic prompts")
    for cat in {i.category for i in corpus}:
        n = sum(1 for i in corpus if i.category == cat)
        print(f"  {cat}: {n}")
